import { useEffect, useState, type FormEvent } from 'react';
import { api } from '@/lib/appdeploy-client';
import { CheckCircle2, LoaderCircle, Plus, RefreshCw } from 'lucide-react';
import { useTenantSession } from './AuthenticationGate';
import { apiErrorMessage } from '../lib/api-error';

type School = { id: string; name: string };
type Item = { id: string; name: string; code?: string; startsOn?: string; endsOn?: string; academicYearId?: string; classId?: string; sequence?: number };
type Catalog = { academicYears: Item[]; terms: Item[]; classes: Item[]; sections: Item[]; subjects: Item[]; truncated?: boolean };
type Kind = 'academic-years' | 'terms' | 'classes' | 'sections' | 'subjects';

const labels: Record<Kind, string> = {
  'academic-years': 'Academic year',
  terms: 'Term',
  classes: 'Class',
  sections: 'Section',
  subjects: 'Subject',
};

export default function AcademicConfiguration() {
  const { tenantId } = useTenantSession();
  const [schools, setSchools] = useState<School[]>([]);
  const [schoolId, setSchoolId] = useState('');
  const [kind, setKind] = useState<Kind>('academic-years');
  const [catalog, setCatalog] = useState<Catalog>({ academicYears: [], terms: [], classes: [], sections: [], subjects: [] });
  const [name, setName] = useState('');
  const [code, setCode] = useState('');
  const [startsOn, setStartsOn] = useState('');
  const [endsOn, setEndsOn] = useState('');
  const [academicYearId, setAcademicYearId] = useState('');
  const [classId, setClassId] = useState('');
  const [sequence, setSequence] = useState('1');
  const [busy, setBusy] = useState(false);
  const [loading, setLoading] = useState(false);
  const [failure, setFailure] = useState('');
  const [message, setMessage] = useState('');

  async function loadSchools() {
    const response = await api.get('/api/platform/schools?tenantId=' + encodeURIComponent(tenantId));
    const items = (response.data.items || []) as School[];
    setSchools(items);
    if (!schoolId && items.length) setSchoolId(items[0].id);
  }

  async function loadCatalog(selectedSchool = schoolId) {
    if (!selectedSchool) return;
    setLoading(true);
    setFailure('');
    try {
      const params = new URLSearchParams({ tenantId, schoolId: selectedSchool });
      const response = await api.get('/api/platform/academic-catalog?' + params.toString());
      setCatalog(response.data as Catalog);
    } catch (cause: any) {
      setFailure(apiErrorMessage(cause, 'Unable to load academic configuration.'));
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => { void loadSchools().catch((cause: any) => setFailure(apiErrorMessage(cause, 'Unable to load schools.', false))); }, [tenantId]);
  useEffect(() => { if (schoolId) void loadCatalog(schoolId); }, [schoolId, tenantId]);

  function resetForm() {
    setName('');
    setCode('');
    setStartsOn('');
    setEndsOn('');
    setAcademicYearId('');
    setClassId('');
    setSequence('1');
  }

  async function save(event: FormEvent) {
    event.preventDefault();
    if (!schoolId) return;
    setBusy(true);
    setFailure('');
    setMessage('');
    const payload: Record<string, unknown> = { name: name.trim() };
    if (kind === 'academic-years') Object.assign(payload, { startsOn, endsOn });
    if (kind === 'terms') Object.assign(payload, { academicYearId, sequence: Number(sequence), startsOn, endsOn });
    if (['classes', 'subjects'].includes(kind)) Object.assign(payload, { code: code.trim() });
    if (kind === 'sections') Object.assign(payload, { code: code.trim(), classId });
    try {
      await api.post('/api/platform/academic-catalog/' + kind + '?tenantId=' + encodeURIComponent(tenantId) + '&schoolId=' + encodeURIComponent(schoolId), payload);
      resetForm();
      await loadCatalog(schoolId);
      setMessage(labels[kind] + ' saved successfully.');
    } catch (cause: any) {
      setFailure(apiErrorMessage(cause, 'Unable to save academic reference.'));
    } finally {
      setBusy(false);
    }
  }

  const entries = [
    { title: 'Academic years', items: catalog.academicYears },
    { title: 'Terms', items: catalog.terms },
    { title: 'Classes', items: catalog.classes },
    { title: 'Sections', items: catalog.sections },
    { title: 'Subjects', items: catalog.subjects },
  ];

  return <div className='config-page'>
    <div className='page-heading'><div className='eyebrow'>ACADEMIC FOUNDATION</div><h1>Academic configuration</h1><p>Maintain school-scoped academic years, terms, classes, sections and subjects. All record identifiers are generated by the server.</p></div>
    <section className='panel config-category'>
      <div className='panel-head'><div><h2>School academic registry</h2><p>Only active schools and records belonging to the selected school are shown.</p></div><button className='btn secondary' onClick={() => void loadCatalog()} disabled={!schoolId || loading}><RefreshCw size={15}/> Refresh</button></div>
      {schools.length ? <label className='config-field'>School<select value={schoolId} onChange={event => setSchoolId(event.target.value)}>{schools.map(school => <option key={school.id} value={school.id}>{school.name}</option>)}</select></label> : <p>Create an active school before configuring its academic records.</p>}
      {failure && <div className='config-error'>{failure}</div>}
      {message && <div className='config-success'><CheckCircle2 size={15}/>{message}</div>}
      {schoolId && <form className='rpm-create' onSubmit={save}>
        <label>Record type<select value={kind} onChange={event => { setKind(event.target.value as Kind); resetForm(); }}><option value='academic-years'>Academic year</option><option value='terms'>Term</option><option value='classes'>Class</option><option value='sections'>Section</option><option value='subjects'>Subject</option></select></label>
        <label>Name<input value={name} onChange={event => setName(event.target.value)} minLength={2} maxLength={100} required/></label>
        {['classes', 'sections', 'subjects'].includes(kind) && <label>Code<input value={code} onChange={event => setCode(event.target.value)} maxLength={30} required/></label>}
        {kind === 'academic-years' && <><label>Starts on<input type='date' value={startsOn} onChange={event => setStartsOn(event.target.value)} required/></label><label>Ends on<input type='date' value={endsOn} onChange={event => setEndsOn(event.target.value)} required/></label></>}
        {kind === 'terms' && <><label>Academic year<select value={academicYearId} onChange={event => setAcademicYearId(event.target.value)} required><option value=''>Select academic year</option>{catalog.academicYears.map(item => <option key={item.id} value={item.id}>{item.name}</option>)}</select></label><label>Term sequence<input type='number' min='1' max='20' value={sequence} onChange={event => setSequence(event.target.value)} required/></label><label>Starts on<input type='date' value={startsOn} onChange={event => setStartsOn(event.target.value)} required/></label><label>Ends on<input type='date' value={endsOn} onChange={event => setEndsOn(event.target.value)} required/></label></>}
        {kind === 'sections' && <label>Class<select value={classId} onChange={event => setClassId(event.target.value)} required><option value=''>Select class</option>{catalog.classes.map(item => <option key={item.id} value={item.id}>{item.name}</option>)}</select></label>}
        <button className='btn primary' disabled={busy || loading || !schools.length}><Plus size={15}/>{busy ? 'Saving…' : 'Add ' + labels[kind].toLowerCase()}</button>
      </form>}
      <div className='config-settings'>
        {entries.map(entry => <div className='config-setting' key={entry.title}><div className='config-setting-label'><b>{entry.title}</b><span>{entry.items.length} active records</span><small>{entry.items.slice(0, 12).map(item => item.name + (item.code ? ' (' + item.code + ')' : '')).join(' · ') || 'No records configured yet.'}</small></div></div>)}
      </div>
      {catalog.truncated && <p className='student-footnote'>The registry has more than 100 records in at least one category. This screen currently displays the first 100; pagination will be added before larger deployments.</p>}
      {loading && <div className='config-loading'><LoaderCircle size={16}/> Loading academic records…</div>}
    </section>
  </div>;
}
