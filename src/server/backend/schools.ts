import { db, error, json, requireAuth } from '@/server/appdeploy-sdk';
import { apiFailure, auditRecord, authorizeRecord, domainEvent, tenantAccessFromRequest, tenantTable } from './platform';

const now = () => new Date().toISOString();

async function getAccess(ctx: any) {
  const resolved = await tenantAccessFromRequest(ctx, {
    allowBodyFallback: false,
    requireTenantId: true,
    maxTenantLength: 128,
    invalidTenantMessage: 'A valid tenantId query parameter is required.',
    membershipMessage: 'Tenant membership not found or access denied.',
  });
  if (!resolved.ok) return { response: resolved.response };
  return { tenantId: resolved.tenantId, membership: resolved.membership, response: null };
}

export const schoolRoutes = {
  'GET /api/platform/schools': [
    requireAuth(),
    async (ctx: any) => {
      try {
        const access = await getAccess(ctx);
        if (access.response !== null) return access.response;
        const limit = ctx.query.limit === undefined ? 100 : Number(ctx.query.limit);
        if (!Number.isInteger(limit) || limit < 1 || limit > 100) return error('limit must be an integer from 1 to 100.', 400);
        const page = await db.list<Record<string, any>>(tenantTable('schools', access.tenantId), {
          limit,
          ...(ctx.query.nextToken ? { nextToken: ctx.query.nextToken } : {}),
        });
        const visible = [];
        for (const school of page.items) {
          if (school.tenantId !== access.tenantId || school.status !== 'active') continue;
          if (await authorizeRecord(access.tenantId, access.membership, 'school', 'read', school)) visible.push(school);
        }
        return json({ items: visible, nextToken: page.nextToken || null, pageSize: limit });
      } catch (cause) {
        return apiFailure(cause, 'Unable to retrieve schools. Please retry.', {
          logLabel: 'school.list failed',
        });
      }
    },
  ],
  'POST /api/platform/schools': [
    requireAuth(),
    async (ctx: any) => {
      try {
        const access = await getAccess(ctx);
        if (access.response !== null) return access.response;
        const body = (ctx.body || {}) as Record<string, unknown>;
        if (Object.keys(body).some(key => !['tenantId', 'name'].includes(key))) return error('School IDs are generated by the server; submit only the school name.', 400);
        const name = typeof body.name === 'string' ? body.name.trim() : '';
        if (name.length < 2 || name.length > 120) return error('School name must contain 2 to 120 characters.', 400);
        const id = crypto.randomUUID();
        const timestamp = now();
        const school = {
          id,
          schoolId: id,
          tenantId: access.tenantId,
          name,
          status: 'active',
          version: 1,
          createdAt: timestamp,
          createdBy: ctx.user.userId,
          updatedAt: timestamp,
          updatedBy: ctx.user.userId,
        };
        if (!(await authorizeRecord(access.tenantId, access.membership, 'school', 'create', school))) return error('Permission denied for school creation.', 403);
        await db.transact([
          db.tx.add(tenantTable('schools', access.tenantId), [school]),
          db.tx.add(tenantTable('audit_events', access.tenantId), [auditRecord(access.tenantId, ctx.user.userId, 'school.created', id, { name })]),
          db.tx.add(tenantTable('domain_events', access.tenantId), [domainEvent(access.tenantId, ctx.user.userId, 'school.created', 'school', id, { name }, crypto.randomUUID(), timestamp)]),
        ]);
        return json({ school }, 201);
      } catch (cause) {
        return apiFailure(cause, 'Unable to create the school. Please retry.', {
          logLabel: 'school.create failed',
        });
      }
    },
  ],
};
