import { db, error, json, requireAuth } from '@/server/appdeploy-sdk';
import { tenantAccessFromRequest, tenantTable, auditRecord, isTenantSuperAdmin, isValidRecordId } from './platform';

const validId = isValidRecordId;
async function access(ctx: any) {
  const resolved = await tenantAccessFromRequest(ctx, {
    requireTenantId: true,
    invalidTenantMessage: 'Tenant ID is required',
    invalidTenantStatus: 400,
  });
  if (!resolved.ok) return { response: resolved.response };
  const { tenantId, membership } = resolved;
  if (!isTenantSuperAdmin(membership)) return { response: error('Only the tenant super administrator can manage teaching assignments', 403) };
  return { tenantId, membership, response: null };
}

export const scopeRoutes = {
  'GET /api/platform/teaching-assignments': [requireAuth(), async (ctx: any) => {
    const a = await access(ctx); if (a.response) return a.response;
    const { items } = await db.list<Record<string, any>>(tenantTable('teaching_assignments', a.tenantId!), { limit: 200 });
    return json({ items: items.filter(x => x.tenantId === a.tenantId && x.status === 'active') });
  }],
  'POST /api/platform/teaching-assignments': [requireAuth(), async (ctx: any) => {
    const a = await access(ctx); if (a.response) return a.response;
    const b = ctx.body || {};
    if (Object.keys(b).some((key: string) => !['tenantId','teacherUserId','schoolId','classId','subjectId','academicYearId','termId'].includes(key))) return error('Teaching-assignment IDs are generated by the server; submit only existing relationship selections.', 400);
    const required = ['teacherUserId','schoolId','classId','subjectId','academicYearId'];
    if (required.some(k => !validId(b[k])) || (b.termId != null && !validId(b.termId))) return error('Provide valid teacher, school, class, subject and academic-year IDs; term ID is optional', 400);
    const id = crypto.randomUUID();
    const assignment = { id, tenantId: a.tenantId, teacherUserId: b.teacherUserId, schoolId: b.schoolId, classId: b.classId, subjectId: b.subjectId, academicYearId: b.academicYearId, termId: b.termId || null, status: 'active', createdBy: ctx.user.userId, createdAt: new Date().toISOString() };
    await db.transact([
      db.tx.add(tenantTable('teaching_assignments', a.tenantId!), [assignment]),
      db.tx.add(tenantTable('audit_events', a.tenantId!), [auditRecord(a.tenantId!, ctx.user.userId, 'teaching-assignment.created', id, { teacherUserId: b.teacherUserId, schoolId: b.schoolId, classId: b.classId, subjectId: b.subjectId, academicYearId: b.academicYearId, termId: b.termId || null })])
    ]);
    return json({ assignment }, 201);
  }],
  'DELETE /api/platform/teaching-assignments/:assignmentId': [requireAuth(), async (ctx: any) => {
    const a = await access(ctx); if (a.response) return a.response;
    const id = String(ctx.params.assignmentId || '');
    const [old] = await db.get<Record<string, any>>(tenantTable('teaching_assignments', a.tenantId!), [id], { consistent: true });
    if (!old || old.tenantId !== a.tenantId) return error('Teaching assignment not found', 404);
    if (old.status !== 'active') return json({ deactivated: true });
    const updated = { ...old, status: 'inactive', deactivatedBy: ctx.user.userId, deactivatedAt: new Date().toISOString() };
    await db.transact([
      db.tx.update(tenantTable('teaching_assignments', a.tenantId!), [{ id, if: { status: 'active' }, record: updated }]),
      db.tx.add(tenantTable('audit_events', a.tenantId!), [auditRecord(a.tenantId!, ctx.user.userId, 'teaching-assignment.deactivated', id, { teacherUserId: old.teacherUserId, classId: old.classId, subjectId: old.subjectId })])
    ]);
    return json({ deactivated: true });
  }]
};
